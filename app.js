function getIssueStructureStatus(issue) {
  if (issue.risk === "red") return { label: "红色安全卡", ok: true, type: "safe" };
  if (hasPilotLessonFlow(issue)) return { label: "新手步骤卡", ok: true, type: "strong" };
  return { label: "基础结构", ok: false, type: "todo" };
}

