function handleManualPreviewClick(target) {
  const closeButton = target.closest("[data-manual-close]");
  if (closeButton) {
    closeManualPreview();
    return true;
  }

  const previewButton = target.closest("[data-manual-preview]");
  if (!previewButton) return false;
  openManualPreview({
    image: previewButton.dataset.manualPreview,
    page: previewButton.dataset.manualPage,
    title: previewButton.dataset.manualTitle
  });
  return true;
}

function getNextStepItems(issue) {
  const items = [];
  const seen = new Set();
  const add = (item) => {
    const key = item.href || item.id || item.query || item.label;
    if (!key || seen.has(key)) return;
    seen.add(key);
    items.push(item);
  };

  (issue.links || []).forEach((link) => add({ type: "入口", label: link.label, href: link.href }));

  ISSUES
    .filter((item) => item.id !== issue.id && item.category === issue.category)
    .slice(0, 3)
    .forEach((item) => add({ type: "同类教程", label: item.title, id: item.id }));

  if (issue.glossary?.[0]) {
    add({
      type: "名词解释",
      label: `查词典：${issue.glossary[0].term}`,
      href: `./glossary.html?term=${encodeURIComponent(issue.glossary[0].term)}`
    });
  }

  return items.slice(0, 5);
}

function renderNextSteps(issue) {
  const items = getNextStepItems(issue);
  if (!items.length) return "";
  return `
    <section class="next-steps">
      <div>
        <span>NEXT</span>
        <h3>接下来你可能还需要</h3>
      </div>
      <div class="next-step-grid">
        ${items.map((item) => item.href
          ? `<a href="${escapeHtml(item.href)}"><small>${escapeHtml(item.type)}</small><strong>${escapeHtml(item.label)}</strong></a>`
          : `<button type="button" data-id="${escapeHtml(item.id)}"><small>${escapeHtml(item.type)}</small><strong>${escapeHtml(item.label)}</strong></button>`
        ).join("")}
      </div>
    </section>
  `;
}

