function updateResults(preferredId) {
  const matches = getMatches();
  const selected = preferredId ? ISSUES.find((issue) => issue.id === preferredId) : matches[0];
  renderGuide(matches);
  renderList(matches);
  if (selected) renderDetail(selected);
}

function scrollToResults(behavior = "smooth") {
  document.querySelector(".layout")?.scrollIntoView({ behavior, block: "start" });
}

function setQuery(query) {
  if (els.query) els.query.value = query;
  const url = new URL(window.location.href);
  if (query) url.searchParams.set("query", query);
  else url.searchParams.delete("query");
  window.history.replaceState({}, "", url);
  updateResults();
  scrollToResults();
}

function bindEvents() {
  els.query?.addEventListener("input", () => updateResults());
  els.clearBtn?.addEventListener("click", () => setQuery(""));
  document.addEventListener("click", (event) => {
    if (handleManualPreviewClick(event.target)) {
      event.preventDefault();
      return;
    }

    const searchIntent = event.target.closest('a[href="#searchMode"]');
    if (searchIntent) {
      window.setTimeout(() => {
        els.query?.focus();
        document.querySelector(".search-panel")?.classList.add("search-panel-active");
      }, 120);
    }
    const queryButton = event.target.closest("[data-query]");
    if (queryButton) {
      event.preventDefault();
      setQuery(queryButton.dataset.query || queryButton.textContent.trim());
      return;
    }
    const chipToggle = event.target.closest("[data-chip-toggle]");
    if (chipToggle) {
      chipsExpanded = !chipsExpanded;
      renderChips();
      return;
    }
    const chipCategory = event.target.closest("[data-chip-category]");
    if (chipCategory) {
      activeChipGroup = Number(chipCategory.dataset.chipCategory || 0);
      chipsExpanded = false;
      renderChips();
      return;
    }
    const idButton = event.target.closest("[data-id]");
    if (idButton) {
      const issue = ISSUES.find((item) => item.id === idButton.dataset.id);
      if (issue) {
        renderDetail(issue);
        scrollToResults();
      }
    }
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeManualPreview();
  });
}

function init() {
  const params = new URLSearchParams(window.location.search);
  const query = params.get("query") || "";
  if (els.query) els.query.value = query;
  const showCoverageDebug = setupDevPanels();
  renderChips();
  renderOnboarding();
  renderIconGuide();
  renderRiskBoard();
  if (showCoverageDebug) renderCoverageBoard();
  updateResults();
  if (query) window.setTimeout(() => scrollToResults("auto"), 80);
}

bindEvents();
init();
