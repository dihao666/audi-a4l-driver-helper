function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "\"": "&quot;",
    "'": "&#39;"
  })[char]);
}

function riskClass(issue) {
  return `risk-${issue.risk || "green"}`;
}

function normalizeQuery(query) {
  return String(query || "").toLowerCase().replace(/\s+/g, "");
}

function detectSearchIntent(query) {
  const q = normalizeQuery(query);
  if (!q) return null;
  return searchIntents.find((intent) => intent.match.some((word) => q.includes(normalizeQuery(word)))) || null;
}

function scoreIssue(issue, query) {
  if (!query) return 1;
  const text = [issue.title, issue.category, issue.quickAnswer, ...(issue.keywords || [])].join(" ").toLowerCase();
  const q = query.toLowerCase().trim();
  const intent = detectSearchIntent(query);
  let score = 0;
  if (issue.title.toLowerCase().includes(q)) score += 80;
  if ((issue.keywords || []).some((k) => q.includes(k.toLowerCase()) || k.toLowerCase().includes(q))) score += 50;
  if (intent?.boosts.includes(issue.id)) {
    const order = intent.boosts.indexOf(issue.id);
    score += 120 - order * 8;
  }
  if (intent?.id === "warning-light" && issue.risk === "red") {
    const hasSpecificWarningWord = ["胎压", "轮胎", "机油", "冷却液", "水温", "车灯", "远光"].some((word) => q.includes(word));
    score += hasSpecificWarningWord ? 50 : 140;
  }
  if ((q.includes("胎压") || q.includes("轮胎")) && issue.id === "tire-pressure-warning") score += 220;
  if (q.includes("机油") && issue.id === "engine-oil-warning") score += 220;
  if ((q.includes("冷却液") || q.includes("水温")) && issue.id === "coolant-warning") score += 220;
  if ((q.includes("自动驻车") || q.includes("autohold") || q.includes("ahold") || q.includes("电子手刹")) && issue.id === "parking-brake-auto-hold") score += 240;
  if ((q.includes("倒车影像") || q.includes("后视摄像头") || q.includes("雷达没反应")) && issue.id === "reverse-camera-sensor") score += 240;
  if (q.includes("车灯") && issue.id === "auto-light-mode") score += 180;
  if (q.includes("远光") && issue.id === "high-beam-assist") score += 180;
  for (const token of q.split(/\s+/).filter(Boolean)) {
    if (text.includes(token)) score += 8;
  }
  for (const char of q) {
    if (char.trim() && text.includes(char)) score += 1;
  }
  return score;
}

function getMatches() {
  const query = els.query?.value.trim() || "";
  return ISSUES
    .map((issue) => ({ issue, score: scoreIssue(issue, query) }))
    .filter((item) => !query || item.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.issue);
}

